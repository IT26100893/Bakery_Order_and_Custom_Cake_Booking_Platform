CREATE TABLE IF NOT EXISTS users (
    id VARCHAR(20) PRIMARY KEY, role VARCHAR(10) NOT NULL,
    name VARCHAR(100) NOT NULL, email VARCHAR(100) NOT NULL, phone VARCHAR(20) NOT NULL,
    password_hash VARCHAR(100) NOT NULL DEFAULT '');

CREATE TABLE IF NOT EXISTS products (
    id VARCHAR(20) PRIMARY KEY, category VARCHAR(10) NOT NULL, name VARCHAR(100) NOT NULL,
    price DOUBLE NOT NULL, stock INT NOT NULL, detail VARCHAR(100));

CREATE TABLE IF NOT EXISTS bookings (
    id VARCHAR(20) PRIMARY KEY, user_id VARCHAR(20) NOT NULL DEFAULT '',
    customer_name VARCHAR(100) NOT NULL, phone VARCHAR(20) NOT NULL,
    flavour VARCHAR(100) NOT NULL, size_kg DOUBLE NOT NULL, message VARCHAR(255),
    pickup_date VARCHAR(10) NOT NULL, status VARCHAR(15) NOT NULL);

CREATE TABLE IF NOT EXISTS orders (
    id VARCHAR(20) PRIMARY KEY, user_id VARCHAR(20) NOT NULL DEFAULT '',
    customer_name VARCHAR(100) NOT NULL,
    status VARCHAR(15) NOT NULL, payment_type VARCHAR(10) NOT NULL);

CREATE TABLE IF NOT EXISTS order_items (
    id INT AUTO_INCREMENT PRIMARY KEY, order_id VARCHAR(20) NOT NULL, product_id VARCHAR(20) NOT NULL,
    product_name VARCHAR(100) NOT NULL, qty INT NOT NULL, unit_price DOUBLE NOT NULL,
    FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE);

-- Upgrade older databases (XAMPP's MariaDB supports IF NOT EXISTS here)
ALTER TABLE users ADD COLUMN IF NOT EXISTS password_hash VARCHAR(100) NOT NULL DEFAULT '';
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS user_id VARCHAR(20) NOT NULL DEFAULT '';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS user_id VARCHAR(20) NOT NULL DEFAULT '';
